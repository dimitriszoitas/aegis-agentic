const packageName = '@dimitriszoitas/aegis-ui';
const docsBase = 'https://dimitriszoitas.github.io/aegis-ui/?path=/docs/';
const v = (name: string, values: string[], defaultValue?: string): CatalogueVariant => ({
  name,
  values,
  ...(defaultValue === undefined ? {} : { default: defaultValue }),
});
interface Example {
  exports: string;
  jsx: string;
  setup?: string;
  imports?: string[];
  subpath?: string;
}
function entry(
  id: string,
  name: string,
  category: string,
  description: string,
  usage: string,
  anatomy: string[],
  example: Example,
  story: string,
  variants: CatalogueVariant[] = [],
  keywords: string[] = [],
): ComponentCatalogueEntry {
  const importPath = `${packageName}/${example.subpath ?? id}`;
  const code = [
    ...(example.setup?.includes('useState') ? ["import { useState } from 'react';"] : []),
    `import { ${example.exports} } from '${importPath}';`,
    ...(example.imports ?? []),
    `import '${packageName}/styles.css';`,
    '',
    'export default function Example() {',
    ...(example.setup ? example.setup.split('\n').map((line) => `  ${line}`) : []),
    '  return (',
    ...example.jsx.split('\n').map((line) => `    ${line}`),
    '  );',
    '}',
  ].join('\n');
  return {
    id,
    name,
    category,
    description,
    purpose: description,
    usage,
    importPath,
    code,
    anatomy,
    variants,
    docsUrl: `${docsBase}${story}--docs`,
    keywords: [id, category, ...keywords],
  };
}
